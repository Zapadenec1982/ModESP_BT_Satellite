#!/usr/bin/env python3
"""Generate main/audio_asrc_table.h, the fractional-delay filter bank of the slave-mode
converter (main/audio_asrc.c), and say how accurate it is.

Row p holds the 16 taps that read the input p/512 of a sample past the centre-left one:
a Kaiser-windowed sinc (beta 14, cut-off at Nyquist), each row scaled to a DC gain of
exactly one so the level cannot move with the phase. The converter interpolates linearly
between neighbouring rows.

The error it reports is the worst |H(w) - e^(-jwd)| over every delay and every frequency up
to 20 kHz at 96 kHz, with the float32 table and the row interpolation the converter does:
what a full-scale 20 kHz sine gets, and the most that anything audible gets.

    python tools/gen_audio_asrc_table.py            # write the header
    python tools/gen_audio_asrc_table.py --check    # and report its error
"""
import argparse
import cmath
import math
import struct
from pathlib import Path

TAPS = 16
PHASES = 512
BETA = 14.0
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "main" / "audio_asrc_table.h"


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-17 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def f32(v):
    return struct.unpack("<f", struct.pack("<f", v))[0]


def row(mu):
    centre = TAPS // 2 - 1
    ib = i0(BETA)
    h = []
    for k in range(TAPS):
        x = k - centre - mu
        t = x / (TAPS / 2)
        w = i0(BETA * math.sqrt(1.0 - t * t)) / ib if abs(t) < 1.0 else 0.0
        s = math.sin(math.pi * x) / (math.pi * x) if abs(x) > 1e-12 else 1.0
        h.append(s * w)
    g = sum(h)
    return [f32(v / g) for v in h]


def table():
    return [row(p / PHASES) for p in range(PHASES + 1)]


def worst_error(tab, fmax=20000.0, fs=96000.0, nmu=193, nw=32):
    centre = TAPS // 2 - 1
    worst = 0.0
    for i in range(nmu):
        mu = (i + 0.37) / nmu               # off the table's own rows on purpose
        p = min(int(mu * PHASES), PHASES - 1)
        f = f32(mu * PHASES - p)
        a, b = tab[p], tab[p + 1]
        c = [f32(a[k] + f32(f * f32(b[k] - a[k]))) for k in range(TAPS)]
        for j in range(nw + 1):
            w = 2 * math.pi * fmax / fs * j / nw
            H = sum(c[k] * cmath.exp(-1j * w * k) for k in range(TAPS))
            worst = max(worst, abs(H - cmath.exp(-1j * w * (centre + mu))))
    return 20 * math.log10(worst)


def write(tab):
    lines = [
        "/* Generated by tools/gen_audio_asrc_table.py -- edit that, not this. */",
        "#pragma once",
        "",
        "/* %d phases + 1 rows x %d taps: Kaiser-windowed sinc, beta %g, unity DC gain. */"
        % (PHASES, TAPS, BETA),
        "#define AUDIO_ASRC_TABLE_TAPS    %du" % TAPS,
        "#define AUDIO_ASRC_TABLE_PHASES  %du" % PHASES,
        "#define AUDIO_ASRC_TABLE_PHASE_BITS %du" % (PHASES.bit_length() - 1),
        "",
        "static const float audio_asrc_table[AUDIO_ASRC_TABLE_PHASES + 1u][AUDIO_ASRC_TABLE_TAPS] = {",
    ]
    for r in tab:
        vals = ", ".join("%.9ef" % v for v in r)
        lines.append("    { %s }," % vals)
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="also report the worst error")
    args = ap.parse_args()
    tab = table()
    write(tab)
    print("wrote %s" % OUT.relative_to(ROOT))
    if args.check:
        print("worst error to 20 kHz at 96 kHz: %.1f dB" % worst_error(tab))


if __name__ == "__main__":
    main()
