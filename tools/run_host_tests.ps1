<#
.SYNOPSIS
    Builds and runs link-layer and BTA reopen tests, with no board involved.

.DESCRIPTION
    components/satlink has no ESP-IDF dependencies precisely so that this is
    possible: framing bugs are far cheaper to find in a terminal than over a UART.
    The BTA regression also needs components/bt generated by setup.ps1.

.PARAMETER Cc
    The host C compiler. The directory it lives in is prepended to PATH, because a
    MSYS2 gcc cannot find its own cc1 without it and fails with no message at all.
.PARAMETER Python
    Python 3 used for extracting production BTA source for the regression replay.
#>

[CmdletBinding()]
param(
    [string]$Cc = 'C:\msys64\ucrt64\bin\gcc.exe',
    [string]$Python = 'python'
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$outDir   = Join-Path $repoRoot 'build\host'
$exe      = Join-Path $outDir 'test_satlink.exe'

if (-not (Test-Path $Cc)) {
    Write-Host "run_host_tests: no C compiler at $Cc. Pass -Cc <path to gcc>." -ForegroundColor Red
    exit 1
}
$env:PATH = "$(Split-Path -Parent $Cc);$env:PATH"

New-Item -ItemType Directory -Force -Path $outDir | Out-Null

$sources = @(
    (Join-Path $repoRoot 'tests\host\main.c'),
    (Join-Path $repoRoot 'tests\host\test_format_sync.c'),
    (Join-Path $repoRoot 'tests\host\test_satlink.c'),
    (Join-Path $repoRoot 'tests\host\test_messages.c'),
    (Join-Path $repoRoot 'tests\host\test_golden.c'),
    (Join-Path $repoRoot 'components\satlink\cobs.c'),
    (Join-Path $repoRoot 'components\satlink\crc16.c'),
    (Join-Path $repoRoot 'components\satlink\frame.c'),
    (Join-Path $repoRoot 'components\satlink\codec.c'),
    (Join-Path $repoRoot 'components\satlink\messages.c')
)

$cflags = @(
    '-std=c17', '-Wall', '-Wextra', '-Werror',
    '-g', '-O1',
    "-I$(Join-Path $repoRoot 'components\satlink\include')",
    "-I$(Join-Path $repoRoot 'tests\host')"
)

# The undefined-behaviour sanitizer is worth having and not worth requiring: a
# MSYS2 gcc often ships without libubsan, and refusing to run the tests over a
# missing optional library would be the wrong trade. Probe, then decide.
$probe = Join-Path $outDir 'ubsan_probe.c'
Set-Content -Path $probe -Encoding ascii -Value 'int main(void){return 0;}'
# Start-Process rather than the call operator: a failing probe writes to stderr,
# and PowerShell turns native stderr into a terminating error under this
# preference. Here a failure is the answer, not a problem.
$probeRun = Start-Process -FilePath $Cc -NoNewWindow -Wait -PassThru `
    -ArgumentList @('-fsanitize=undefined', $probe, '-o', (Join-Path $outDir 'ubsan_probe.exe')) `
    -RedirectStandardError (Join-Path $outDir 'ubsan_probe.err') `
    -RedirectStandardOutput (Join-Path $outDir 'ubsan_probe.out')
if ($probeRun.ExitCode -eq 0) {
    $cflags += @('-fsanitize=undefined', '-fno-sanitize-recover=all')
} else {
    Write-Host 'run_host_tests: no libubsan here, running without the sanitizer.' -ForegroundColor Yellow
}

& $Cc @cflags @sources -o $exe
if ($LASTEXITCODE -ne 0) {
    Write-Host 'run_host_tests: compilation failed.' -ForegroundColor Red
    exit 1
}

& $exe
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# The endpoint re-registration machine, pure C out of main/.
$endpointsExe = Join-Path $outDir 'test_endpoints.exe'
& $Cc '-std=c17' '-Wall' '-Wextra' '-Werror' '-g' '-O1' `
    "-I$(Join-Path $repoRoot 'main')" `
    "-I$(Join-Path $repoRoot 'components\satlink\include')" `
    "-I$(Join-Path $repoRoot 'tests\host')" `
    (Join-Path $repoRoot 'tests\host\test_endpoints.c') -o $endpointsExe
if ($LASTEXITCODE -ne 0) {
    Write-Host 'run_host_tests: test_endpoints compilation failed.' -ForegroundColor Red
    exit 1
}
& $endpointsExe
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# Protocol 1.8 on the device side: settings, bonds, pairing, reconnect. Pure C too.
$settingsExe = Join-Path $outDir 'test_bt_settings.exe'
& $Cc '-std=c17' '-Wall' '-Wextra' '-Werror' '-g' '-O1' `
    "-I$(Join-Path $repoRoot 'main')" `
    "-I$(Join-Path $repoRoot 'components\satlink\include')" `
    "-I$(Join-Path $repoRoot 'tests\host')" `
    (Join-Path $repoRoot 'tests\host\test_bt_settings.c') -o $settingsExe
if ($LASTEXITCODE -ne 0) {
    Write-Host 'run_host_tests: test_bt_settings compilation failed.' -ForegroundColor Red
    exit 1
}
& $settingsExe
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# The device's other rules of PROTOCOL.md, pure C out of main/.
$rulesExe = Join-Path $outDir 'test_rules.exe'
& $Cc '-std=c17' '-Wall' '-Wextra' '-Werror' '-g' '-O1' `
    "-I$(Join-Path $repoRoot 'main')" `
    "-I$(Join-Path $repoRoot 'components\satlink\include')" `
    "-I$(Join-Path $repoRoot 'tests\host')" `
    (Join-Path $repoRoot 'tests\host\test_rules.c') -o $rulesExe
if ($LASTEXITCODE -ne 0) {
    Write-Host 'run_host_tests: test_rules compilation failed.' -ForegroundColor Red
    exit 1
}
& $rulesExe
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# Replay the codec-switch race through source extracted from our generated BT.
& $Python (Join-Path $repoRoot 'tools\run_bta_reopen_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# A live PING/PONG link must recover a dropped startup capability greeting.
& $Python (Join-Path $repoRoot 'tools\run_hello_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# A UART event that announces fewer bytes than are buffered must not strand the rest.
& $Python (Join-Path $repoRoot 'tools\run_link_rx_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# Cover buffering must survive fragmented heaps and cancel delayed OBEX pulls.
& $Python (Join-Path $repoRoot 'tools\run_cover_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

& $Python (Join-Path $repoRoot 'tools\run_audio_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

& $Python (Join-Path $repoRoot 'tools\run_audio_refill_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

& $Python (Join-Path $repoRoot 'tools\run_audio_asrc_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

& $Python (Join-Path $repoRoot 'tools\run_lhdc_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# The Helix AAC decoder must refuse malformed frames, not overrun or spin on them.
& $Python (Join-Path $repoRoot 'tools\run_aac_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# The SBC sink offers stereo only and still decodes a mono stream to both channels.
& $Python (Join-Path $repoRoot 'tools\run_sbc_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# Reconnecting as initiator must skip a source SEP that builds no config, not send garbage.
& $Python (Join-Path $repoRoot 'tools\run_sink_getconfig_tests.py') --cc $Cc
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# SET_CONFIGURATION must name one value per field, not pass a 44.1|48 mask for 48 kHz.
& $Python (Join-Path $repoRoot 'tools\run_sink_setconfig_tests.py') --cc $Cc
exit $LASTEXITCODE
